#!/usr/bin/env python3
"""Generate the Clarifo MCP tools reference from the production server.

Two steps, so rendering can be checked without credentials:

  fetch   Connect to the MCP server, read initialize / tools/list /
          prompts/list / resources/list and write a normalised snapshot to
          docs/tools/tools.json. Needs CLARIFO_API_KEY.
  render  Turn docs/tools/tools.json into Markdown pages under docs/tools/
          and record what changed since the previous snapshot in
          docs/tools/CHANGES.md.

Usage:
  CLARIFO_API_KEY=... python scripts/tools_reference/generate.py fetch render
  python scripts/tools_reference/generate.py render          # offline

What is published and what is not:
  - Tool names, descriptions, input/output schemas and annotations are
    published: every connected client already receives them.
  - For `_meta`, only the key names are kept (they show which clients render
    a view). Values can carry internal resource URIs and are dropped.
  - Example responses are never captured automatically. Reviewed examples
    live in docs/tools/examples/<tool>.md and are embedded as-is; see
    docs/tools/examples/README.md for the publication rules.
"""
from __future__ import annotations

import argparse
import asyncio
import datetime as dt
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "tools"
SNAPSHOT = OUT / "tools.json"
EXAMPLES = OUT / "examples"
CATEGORIES = Path(__file__).with_name("categories.json")
DEFAULT_URL = "https://mcp.clarifo.com/mcp"
GENERATED_BANNER = (
    "<!-- Generated by scripts/tools_reference/generate.py from the production "
    "MCP schema. Do not edit by hand. -->"
)

# _meta keys that tell which client renders a view for a tool.
CLIENT_META_HINTS = {
    "openai/outputTemplate": "Renders an in-chat view in ChatGPT (Apps SDK).",
    "openai/widgetAccessible": "The ChatGPT view can call this tool itself.",
    "openai/toolInvocation/invoking": "Shows a status line in ChatGPT while running.",
    "ui/resourceUri": "Renders an MCP Apps view in clients that support it (for example Claude).",
    "ui": "Renders an MCP Apps view in clients that support it (for example Claude).",
}


# --------------------------------------------------------------------- fetch

async def _fetch(url: str, api_key: str) -> dict:
    import httpx
    from mcp import ClientSession
    from mcp.client.streamable_http import streamable_http_client

    headers = {"Authorization": f"Bearer {api_key}", "User-Agent": "clarifo-tools-reference"}
    async with httpx.AsyncClient(headers=headers, timeout=60) as http:
        async with streamable_http_client(url, http_client=http) as (read, write, _):
            async with ClientSession(read, write) as session:
                init = await session.initialize()

                async def paged(method, attr):
                    items, cursor = [], None
                    while True:
                        res = await method(cursor)
                        items.extend(getattr(res, attr))
                        cursor = res.nextCursor
                        if not cursor:
                            return items

                caps = init.capabilities
                tools = await paged(session.list_tools, "tools")
                prompts = await paged(session.list_prompts, "prompts") if caps.prompts else []
                resources = await paged(session.list_resources, "resources") if caps.resources else []
                templates = (await paged(session.list_resource_templates, "resourceTemplates")
                             if caps.resources else [])

    def dump(x):
        return x.model_dump(mode="json", by_alias=True, exclude_none=True)

    def tool(t):
        d = dump(t)
        meta = d.pop("_meta", None) or d.pop("meta", None) or {}
        d["meta_keys"] = sorted(meta.keys())
        return d

    return {
        "server": {
            "name": init.serverInfo.name,
            "version": init.serverInfo.version,
            "protocol_version": init.protocolVersion,
            "url": url,
            "capabilities": sorted(k for k, v in dump(caps).items() if v is not None),
        },
        "tools": sorted((tool(t) for t in tools), key=lambda t: t["name"]),
        "prompts": sorted(({"name": p.name, "description": p.description or "",
                            "arguments": [dump(a) for a in (p.arguments or [])]} for p in prompts),
                          key=lambda p: p["name"]),
        # Resource URIs can point at user-specific items: publish templates
        # and static resource names only, never instance URIs with ids.
        "resource_templates": sorted(({"name": r.name, "uriTemplate": r.uriTemplate,
                                       "description": r.description or ""} for r in templates),
                                     key=lambda r: r["name"]),
        "resources_count": len(resources),
    }


def fetch(url: str) -> None:
    api_key = os.environ.get("CLARIFO_API_KEY")
    if not api_key:
        sys.exit("CLARIFO_API_KEY is not set")
    snap = asyncio.run(_fetch(url, api_key))
    if not snap["tools"]:
        sys.exit("Server returned no tools; refusing to overwrite the snapshot")
    previous = SNAPSHOT.read_text() if SNAPSHOT.exists() else None
    if previous:
        (OUT / ".tools.previous.json").write_text(previous)
    snap["fetched_at"] = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    OUT.mkdir(parents=True, exist_ok=True)
    SNAPSHOT.write_text(json.dumps(snap, indent=2, ensure_ascii=False) + "\n")
    print(f"Fetched {len(snap['tools'])} tools from {snap['server']['name']} {snap['server']['version']}")


# -------------------------------------------------------------------- render

def _type_of(schema: dict) -> str:
    if "anyOf" in schema:
        parts = [_type_of(s) for s in schema["anyOf"] if s.get("type") != "null"]
        return " | ".join(dict.fromkeys(parts)) or "null"
    t = schema.get("type", "any")
    if "enum" in schema:
        return " | ".join(f'`"{v}"`' if isinstance(v, str) else f"`{v}`" for v in schema["enum"])
    if t == "array":
        return f"array of {_type_of(schema.get('items', {}))}"
    return str(t)


def _enum_of(schema: dict) -> list:
    if "enum" in schema:
        return schema["enum"]
    for s in schema.get("anyOf", []):
        if "enum" in s:
            return s["enum"]
    return []


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _params_table(schema: dict) -> str:
    props = schema.get("properties") or {}
    if not props:
        return "_No parameters._\n"
    required = set(schema.get("required") or [])
    rows = ["| Parameter | Type | Required | Default | Description |", "|---|---|---|---|---|"]
    for name, p in props.items():
        typ = _type_of(p)
        if _enum_of(p) and "enum" not in p:
            typ = " | ".join(f'`"{v}"`' for v in _enum_of(p))
        default = "" if "default" not in p or p["default"] is None else f"`{json.dumps(p['default'])}`"
        rows.append(f"| `{name}` | {_cell(typ)} | {'yes' if name in required else ''} | {default} | "
                    f"{_cell(p.get('description', ''))} |")
    return "\n".join(rows) + "\n"


def _clean_description(text: str) -> str:
    """Turn a docstring-style description into Markdown.

    Section headers ("Args:", "Returns:") become bold labels, and indented
    "name: text" entries under them become bullets, with their continuation
    lines folded in, so nothing renders as an accidental code block.
    """
    lines = (text or "").strip("\n").splitlines()
    if not lines:
        return ""
    indents = [len(l) - len(l.lstrip()) for l in lines[1:] if l.strip()]
    pad = min(indents) if indents else 0
    lines = [lines[0].strip()] + [l[pad:].rstrip() for l in lines[1:]]
    out: list[str] = []
    for line in lines:
        stripped = line.strip()
        indent = len(line) - len(line.lstrip())
        if re.fullmatch(r"[A-Z][A-Za-z ]{1,30}:", stripped) and indent == 0:
            out += ["", f"**{stripped[:-1]}**", ""]
        elif indent and (m := re.match(r"([`\w][\w`/ ,.\-]{0,60}?):\s+(.*)", stripped)) and indent <= 4:
            out.append(f"- {m.group(1)}: {m.group(2)}")
        elif indent and stripped.startswith("- ") and indent <= 4:
            out.append(stripped)
        elif indent and stripped and out and out[-1].startswith("- "):
            out[-1] += " " + stripped
        else:
            out.append(stripped)
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()


def _behaviour(t: dict, write_tools: set) -> list[str]:
    a = t.get("annotations") or {}
    notes = []
    if t["name"] in write_tools or a.get("readOnlyHint") is False:
        notes.append("**Writes to the user's Clarifo workspace.** Off until the user enables "
                     "workspace writes under Settings > Integrations; runs only when asked.")
    elif a.get("readOnlyHint"):
        notes.append("Read-only.")
    if a.get("destructiveHint"):
        notes.append("Marked destructive: clients ask for confirmation.")
    if a.get("idempotentHint"):
        notes.append("Idempotent: repeating the call has no extra effect.")
    if a.get("openWorldHint"):
        notes.append("Reaches outside Clarifo's own database (open world).")
    return notes


def _client_notes(t: dict) -> list[str]:
    seen, notes = set(), []
    for k in t.get("meta_keys", []):
        hint = CLIENT_META_HINTS.get(k) or next(
            (v for p, v in CLIENT_META_HINTS.items() if k.startswith(p + "/")), None)
        if hint and hint not in seen:
            seen.add(hint)
            notes.append(hint)
    if not notes:
        notes.append("Returns data only (no client-specific view); works the same in every MCP client.")
    return notes


def _load_categories(names: list[str]):
    cfg = json.loads(CATEGORIES.read_text())["categories"]
    known = {n for c in cfg for n in c["tools"]}
    groups = [(c["title"], [n for n in c["tools"] if n in names]) for c in cfg]
    other = sorted(set(names) - known)
    if other:
        groups.append(("Other", other))
    write_tools = set(next((c["tools"] for c in cfg if c["id"] == "workspace_write"), []))
    stale = sorted(known - set(names))
    return [(t, ns) for t, ns in groups if ns], write_tools, other, stale


def _first_sentence(text: str) -> str:
    text = " ".join((text or "").split())
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    return (m.group(1) if m else text)[:200]


def _diff(prev: dict | None, cur: dict) -> list[str]:
    if not prev:
        return []
    p = {t["name"]: t for t in prev.get("tools", [])}
    c = {t["name"]: t for t in cur["tools"]}
    lines = [f"- Added: `{n}`" for n in sorted(c.keys() - p.keys())]
    lines += [f"- Removed: `{n}`" for n in sorted(p.keys() - c.keys())]
    for n in sorted(c.keys() & p.keys()):
        a, b = p[n].get("inputSchema", {}), c[n].get("inputSchema", {})
        ap, bp = set((a.get("properties") or {})), set((b.get("properties") or {}))
        changes = [f"+`{x}`" for x in sorted(bp - ap)] + [f"-`{x}`" for x in sorted(ap - bp)]
        if set(a.get("required") or []) != set(b.get("required") or []):
            changes.append("required parameters changed")
        if p[n].get("annotations") != c[n].get("annotations"):
            changes.append("annotations changed")
        if p[n].get("description") != c[n].get("description"):
            changes.append("description changed")
        if changes:
            lines.append(f"- Changed: `{n}` ({', '.join(changes)})")
    return lines


def render() -> None:
    if not SNAPSHOT.exists():
        sys.exit(f"{SNAPSHOT.relative_to(ROOT)} not found; run `fetch` first")
    snap = json.loads(SNAPSHOT.read_text())
    tools = snap["tools"]
    names = [t["name"] for t in tools]
    groups, write_tools, uncategorised, stale = _load_categories(names)
    server = snap["server"]

    # One page per tool.
    for old in OUT.glob("*.md"):
        if old.name not in {"README.md", "CHANGES.md", "clients.md"}:
            old.unlink()
    for t in tools:
        parts = [GENERATED_BANNER, "", f"# `{t['name']}`", ""]
        if t.get("title"):
            parts += [f"_{t['title']}_", ""]
        parts += [_clean_description(t.get("description", "")), "", "## Parameters", "",
                  _params_table(t.get("inputSchema") or {})]
        if t.get("outputSchema"):
            parts += ["## Output schema", "", "```json",
                      json.dumps(t["outputSchema"], indent=2, ensure_ascii=False), "```", ""]
        parts += ["## Behaviour", ""] + [f"- {n}" for n in _behaviour(t, write_tools)] + [""]
        parts += ["## Clients", ""] + [f"- {n}" for n in _client_notes(t)] + [
            "", "See [client differences](clients.md).", ""]
        example = EXAMPLES / f"{t['name']}.md"
        if example.exists():
            parts += ["## Example", "", example.read_text().strip(), ""]
        parts += ["## Input schema (JSON)", "", "<details><summary>Show</summary>", "", "```json",
                  json.dumps(t.get("inputSchema") or {}, indent=2, ensure_ascii=False), "```", "",
                  "</details>", ""]
        (OUT / f"{t['name']}.md").write_text("\n".join(parts))

    # Index.
    idx = [GENERATED_BANNER, "", "# Clarifo MCP tools reference", "",
           f"{len(tools)} tools on `{server['url']}`, server `{server['name']}` "
           f"version {server['version']}, MCP protocol {server['protocol_version']}. "
           f"Snapshot taken {snap.get('fetched_at', 'unknown')}.", "",
           "Generated from the production server's MCP schema by "
           "[`scripts/tools_reference`](../../scripts/tools_reference/). "
           "The machine-readable snapshot is [`tools.json`](tools.json); "
           "what changed between snapshots is in [`CHANGES.md`](CHANGES.md).", ""]
    for title, ns in groups:
        idx += [f"## {title}", "", "| Tool | What it does |", "|---|---|"]
        by = {t["name"]: t for t in tools}
        for n in ns:
            idx.append(f"| [`{n}`]({n}.md) | {_cell(_first_sentence(by[n].get('description', '')))} |")
        idx.append("")
    if snap.get("prompts"):
        idx += ["## Prompts", "", "| Prompt | Description |", "|---|---|"]
        idx += [f"| `{p['name']}` | {_cell(p['description'])} |" for p in snap["prompts"]] + [""]
    (OUT / "README.md").write_text("\n".join(idx))

    # Change log for the tool surface.
    prev_path = OUT / ".tools.previous.json"
    prev = json.loads(prev_path.read_text()) if prev_path.exists() else None
    changes = _diff(prev, snap)
    log = OUT / "CHANGES.md"
    header = (GENERATED_BANNER + "\n\n# Tool surface changes\n\n"
              "Detected automatically between production snapshots. "
              "Summaries for people are in the top-level [CHANGELOG](../../CHANGELOG.md).\n")
    body = log.read_text().split("\n## ", 1)[1] if log.exists() and "\n## " in log.read_text() else ""
    entry = []
    if changes or uncategorised or stale:
        entry = [f"## {snap.get('fetched_at', '')[:10]} (server {server['version']})", ""] + changes
        entry += [f"- Not in categories.json yet: `{n}`" for n in uncategorised]
        entry += [f"- In categories.json but not on the server: `{n}`" for n in stale]
        entry.append("")
    log.write_text(header + "\n" + "\n".join(entry) + ("\n## " + body if body else ""))
    if prev_path.exists():
        prev_path.unlink()
    print(f"Rendered {len(tools)} tool pages to {OUT.relative_to(ROOT)}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("steps", nargs="+", choices=["fetch", "render"])
    ap.add_argument("--url", default=os.environ.get("CLARIFO_MCP_URL", DEFAULT_URL))
    args = ap.parse_args()
    if "fetch" in args.steps:
        fetch(args.url)
    if "render" in args.steps:
        render()


if __name__ == "__main__":
    main()
